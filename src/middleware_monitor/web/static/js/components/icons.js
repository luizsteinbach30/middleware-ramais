export function injectIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    if (el.firstElementChild) continue;
    el.innerHTML = svg(el.dataset.icon, parseInt(el.dataset.size || '14', 10));
  }
}

